#!/usr/bin/env python3
"""Generate the "Before you build" box at the top of each spec in docs/specs/.

The box gathers, for one spec, what lives in the cross-cutting docs: the milestone(s) that build it
(plan/roadmap.md), the decisions that apply (plan/decisions.md), the open spikes with their fallbacks
(plan/open-questions.md) and the user journeys it serves (product/user-journeys.md). Agents then see
everything relevant in the file they are reading.

Run after editing those four files or any [SPIKE-n] / ADR reference:  python3 scripts/docs-context.py
With --check it only reports specs whose box is out of date (exit 1), for CI.
"""
import os
import re
import sys

DOCS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs")
SPEC_DIR = os.path.join(DOCS, "specs")
START, END = "<!-- before-you-build:start -->", "<!-- before-you-build:end -->"

# Which milestone builds which part of each spec (plan/roadmap.md is the source; keep in sync).
MILESTONES = {
    "architecture": "M0 (install layout, release pipeline, import-boundary check); later milestones follow the module rules",
    "event-log": "M1 (event log, resume, crash recovery); M2 (blob GC, disk use)",
    "providers": "M1 (Anthropic adapter, retries, adapter-contract proof for 3 protocols); M4 (OpenAI/Open Responses, Chinese providers, Chat fallback, registry, catalog, failover; Google §5 applies to Gemini like any other registry provider)",
    "agent-loop": "M1",
    "tools": "M1 (Read, Write, Edit, Bash/PowerShell, Grep, Glob, AskUserQuestion, TodoWrite, plan-mode tools); M2 (WebFetch, WebSearch); M3 (dialogs)",
    "permissions": "M1 (rules, modes, built-in checks, sensitive files); M2 (sandbox, taint, workspace trust, redaction)",
    "context": "M1 (epochs, prompt assembly, instruction files, mid-epoch instructions); M2 (compaction)",
    "receipts-budgets": "M2 (cost, budgets, daily ledger); M3 (receipts, claim checker)",
    "checkpoints": "M2",
    "tui": "M1 (headless `-p`, output formats, exit codes); M3 (TUI)",
    "cli-config": "M1 (settings, precedence, secrets, startup); M3 (`/login`, first-run wizard, install scripts); M4 (registry-driven providers, OAuth logins)",
    "extensibility": "v0.2 (only the \"v0.1 constraint\" lines apply to v0.1 code)",
    "platforms": "Every milestone (each feature is built for all three OSes)",
    "testing": "Every milestone (each task's tests); M5 (evals, soak, release gates)",
    "interfaces": "M1 (types are created with the modules that own them)",
}
SPECS = sorted(f[:-3] for f in os.listdir(SPEC_DIR) if f.endswith(".md"))
LINK_TO_SPEC = r"\]\((?:\.\./specs/|\./)?([a-z-]+)\.md"


def read(rel):
    with open(os.path.join(DOCS, rel), encoding="utf-8") as f:
        return f.read()


def strip_box(text):
    return re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n*", "", text, flags=re.S)


def parse_adrs():
    text = read("plan/decisions.md")
    adrs = {}
    for m in re.finditer(r"^## ADR-(\d+): (.+?)\n(.*?)(?=^## ADR-|\Z)", text, re.S | re.M):
        n, title, body = m.group(1), m.group(2).strip(), m.group(3)
        if title.startswith("replaced by"):
            continue
        links = set(re.findall(r"\]\(\.\./specs/([a-z-]+)\.md", body))
        adrs[n] = (title.rstrip("."), links)
    return adrs


def parse_spikes():
    text = read("plan/open-questions.md")
    open_part = text.split("## Resolved")[0]
    spikes = {}
    for row in re.findall(r"^\| SPIKE-(\d+) \|(.*)\|\s*$", open_part, re.M):
        n, rest = row
        cols = [c.strip() for c in rest.split(" | ")]
        if len(cols) < 4:
            continue
        question, blocks, _how, fallback = cols[0], cols[1], cols[2], cols[3]
        short = re.sub(r"\s+", " ", question).rstrip(" .")
        spikes[n] = (short, blocks.replace("**", ""), fallback.rstrip(" |"))
    return spikes


def parse_journeys():
    text = read("product/user-journeys.md")
    by_spec = {}
    for m in re.finditer(r"^\| (\w+) \| (.+?) \| (.+?) \|\s*$", text, re.M):
        num, _step, links = m.groups()
        if num == "#" or set(num) <= {"-"}:
            continue
        for s in set(re.findall(r"\(\.\./specs/([a-z-]+)\.md", links)):
            by_spec.setdefault(s, []).append(num)
    return by_spec


def box_for(spec, adrs, spikes, journeys):
    body = strip_box(read(f"specs/{spec}.md"))
    lines = [START, "> **Before you build from this spec** (generated by `scripts/docs-context.py` from the decisions, roadmap, open questions and user journeys; don't edit by hand)"]
    lines.append(f"> - **Milestone:** {MILESTONES.get(spec, 'see [roadmap](../plan/roadmap.md)')}.")
    refs = set(re.findall(r"(?:DECISION|ADR)-(\d+)", body))
    applicable = sorted({n for n in refs if n in adrs} | {n for n, (_, links) in adrs.items() if spec in links}, key=int)
    if applicable:
        lines.append("> - **Decisions that apply** ([decisions](../plan/decisions.md)): " + "; ".join(f"ADR-{n} {adrs[n][0]}" for n in applicable) + ".")
    used = sorted({n for n in re.findall(r"SPIKE-(\d+)", body) if n in spikes}, key=int)
    if used:
        lines.append("> - **Open questions** ([open questions](../plan/open-questions.md)); build the part that depends on one only after it's resolved, or use its fallback:")
        for n in used:
            short, blocks, fallback = spikes[n]
            lines.append(f">   - **SPIKE-{n}** ({blocks}): {short} *If no:* {fallback}")
    else:
        lines.append("> - **Open questions:** none.")
    j = journeys.get(spec)
    if j:
        lines.append(f"> - **User journeys served** ([user journeys](../product/user-journeys.md)): steps {', '.join(j)}. A change here must keep those steps working.")
    lines.append(END)
    return "\n".join(lines) + "\n\n"


def main():
    check = "--check" in sys.argv
    missing = [s for s in SPECS if s not in MILESTONES]
    if missing:
        print("No milestone entry for:", ", ".join(missing))
        sys.exit(1)
    adrs, spikes, journeys = parse_adrs(), parse_spikes(), parse_journeys()
    stale = []
    for spec in SPECS:
        path = os.path.join(SPEC_DIR, f"{spec}.md")
        text = read(f"specs/{spec}.md")
        title, rest = strip_box(text).split("\n", 1)
        new = title + "\n\n" + box_for(spec, adrs, spikes, journeys) + rest.lstrip("\n")
        if new != text:
            stale.append(spec)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
    if check and stale:
        print("Out-of-date 'Before you build' boxes:", ", ".join(stale))
        sys.exit(1)
    print(("checked" if check else "updated"), len(SPECS), "specs;", len(stale), "changed")


if __name__ == "__main__":
    main()
