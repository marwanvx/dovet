#!/usr/bin/env python3
"""Print everything an agent needs to start its next session, in one go.

    python3 scripts/next.py            # where the project stands + the next task + the exact spec text it needs
    python3 scripts/next.py M0-03      # the same for a named task

It reads docs/plan/tasks/ (task lists, PROGRESS.md, QUESTIONS.md) and the spec sections a task's
"Read" line links to, and prints them, so the agent never has to guess which files matter.
The build loop (docs/workflow/build-loop.md) tells agents to run this first.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DOCS = os.path.join(ROOT, "docs")
TASKS = os.path.join(DOCS, "plan", "tasks")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def milestones():
    """Task files in roadmap order (M0, M1, ...)."""
    files = sorted((f for f in os.listdir(TASKS) if re.match(r"M\d+\.md$", f)), key=lambda f: int(f[1:-3]))
    return [(f[:-3], read(os.path.join(TASKS, f))) for f in files]


def parse_tasks(text):
    tasks = []
    for m in re.finditer(r"^### (M\d+-\d+\w*) (.+?)\n(.*?)(?=^### |\Z)", text, re.S | re.M):
        tid, title, body = m.groups()
        status = re.search(r"\*\*Status:\*\*\s*(.+)", body)
        deps = re.search(r"\*\*Depends on:\*\*\s*(.+)", body)
        tasks.append({"id": tid, "title": title.strip(), "body": body.strip(),
                      "status": (status.group(1).strip() if status else "todo"),
                      "deps": (deps.group(1).strip() if deps else "—")})
    return tasks


def is_done(status):
    return status.startswith("done")


def deps_done(task, by_id):
    if task["deps"] in ("—", "-", ""):
        return True
    if task["deps"].startswith("all other"):
        return all(is_done(t["status"]) for t in by_id.values() if t["id"] != task["id"])
    return all(is_done(by_id[d]["status"]) for d in re.findall(r"M\d+-\d+\w*", task["deps"]) if d in by_id)


def sections(doc_text, wanted):
    """Return the parts of a markdown doc whose headings match the wanted § numbers or quoted titles."""
    heads = [(m.start(), len(m.group(1)), m.group(2).strip()) for m in re.finditer(r"^(#{2,4}) (.+)$", doc_text, re.M)]
    out, covered = [], []
    for i, (pos, level, title) in enumerate(heads):
        if any(a <= pos < b for a, b in covered):   # already inside a printed section
            continue
        num = re.match(r"(\d+[a-z]?(?:\.\d+)?)\.?\s", title)
        hit = any((num and num.group(1) == w) or (not w[0].isdigit() and w.lower() in title.lower()) for w in wanted)
        if not hit:
            continue
        end = next((p for p, lv, _ in heads[i + 1:] if lv <= level), len(doc_text))
        covered.append((pos, end))
        out.append(doc_text[pos:end].rstrip())
    return out


def box(doc_text):
    m = re.search(r"<!-- before-you-build:start -->(.*?)<!-- before-you-build:end -->", doc_text, re.S)
    return m.group(1).strip() if m else ""


def reading_for(task):
    read_line = re.search(r"\*\*Read:\*\*(.+)", task["body"])
    if not read_line:
        return []
    out = []
    for label, target in re.findall(r"\[([^\]]+)\]\(([^)#]+)(?:#[^)]*)?\)", read_line.group(1)):
        path = os.path.normpath(os.path.join(TASKS, target))
        if not os.path.isfile(path):
            continue
        text = read(path)
        wanted = re.findall(r"§\s*(\d+[a-z]?(?:\.\d+)?)", label) + re.findall(r"\"([^\"]+)\"", label)
        rel = os.path.relpath(path, ROOT)
        parts = sections(text, wanted) if wanted else []
        for n in re.findall(r"SPIKE-(\d+)", label):   # a spike reference prints its table row
            parts += re.findall(r"^\| SPIKE-" + n + r" \|.*$", text, re.M)
            wanted.append("SPIKE-" + n)
        out.append((rel, label, box(text), parts, bool(wanted)))
    return out


def tail_entries(text, n):
    entries = re.split(r"(?=^## )", text, flags=re.M)
    return "".join([e for e in entries if e.startswith("## ")][-n:])


def main():
    ms = milestones()
    want = sys.argv[1] if len(sys.argv) > 1 else None
    print("# Session start (generated by scripts/next.py)\n")
    q = read(os.path.join(TASKS, "QUESTIONS.md"))
    waiting = q.split("## Waiting for the owner")[1].split("## Answered")[0].strip() if "## Waiting for the owner" in q else ""
    print("## Questions waiting for the owner\n" + (waiting or "(none)") + "\n")
    print("## Last progress entries\n" + tail_entries(read(os.path.join(TASKS, "PROGRESS.md")), 3).strip() + "\n")

    for name, text in ms:
        tasks = parse_tasks(text)
        by_id = {t["id"]: t for t in tasks}
        if want:
            task = by_id.get(want)
            if not task:
                continue
        else:
            if tasks and all(is_done(t["status"]) for t in tasks):
                continue
            task = next((t for t in tasks if t["status"].startswith("in-progress")), None) or \
                next((t for t in tasks if t["status"] == "todo" and deps_done(t, by_id)), None)
        print(f"## Current milestone: {name}  ({sum(is_done(t['status']) for t in tasks)}/{len(tasks)} tasks done)\n")
        if not task:
            blocked = [t["id"] for t in tasks if t["status"].startswith("blocked")]
            print("No task can start now." + (f" Blocked: {', '.join(blocked)} (see QUESTIONS.md)." if blocked else ""))
            return
        print(f"## Task {task['id']} {task['title']}\n\n{task['body']}\n")
        print("## What to read (exact text; read nothing else unless a test failure points you there)\n")
        for rel, label, bx, parts, had_sections in reading_for(task):
            print(f"### {rel} — {label}\n")
            if bx:
                print(bx + "\n")
            if parts:
                print("\n\n".join(parts) + "\n")
            elif had_sections:
                print(f"(Couldn't find those sections automatically: read them in {rel}.)\n")
            else:
                print(f"(Read the whole file: {rel}.)\n")
        return
    if want:
        print(f"Task {want} not found in docs/plan/tasks/.")
    else:
        print("Every task list is finished. Next: plan the next milestone (build loop step 4).")


if __name__ == "__main__":
    main()
